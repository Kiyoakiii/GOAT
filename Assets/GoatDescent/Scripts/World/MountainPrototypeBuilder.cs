        private void CreatePineCrown(Transform parent, Vector3 localPosition, float radius, float height, Material material)
        {
            const int sides = 6;
            var vertices = new List<Vector3> { new Vector3(0f, height * .5f, 0f) };
            var triangles = new List<int>();
            for (int i = 0; i < sides; i++)
            {
                float angle = i * Mathf.PI * 2f / sides;
                float wobble = .82f + (i % 3) * .09f;
                vertices.Add(new Vector3(Mathf.Cos(angle) * radius * wobble, -height * .5f, Mathf.Sin(angle) * radius * wobble));
            }
            for (int i = 0; i < sides; i++) { int next = i == sides - 1 ? 0 : i + 1; triangles.Add(0); triangles.Add(1 + next); triangles.Add(1 + i); }
            var mesh = new Mesh { name = "Sparse pine crown mesh" }; mesh.SetVertices(vertices); mesh.SetTriangles(triangles, 0); mesh.RecalculateNormals();
            var crown = new GameObject("Sparse pine crown"); crown.transform.SetParent(parent); crown.transform.localPosition = localPosition;
            crown.AddComponent<MeshFilter>().sharedMesh = mesh; crown.AddComponent<MeshRenderer>().sharedMaterial = material;
        }

